// npm run starter:build
// Bundles the shared pipeline + ranking into starter/lib/tuberemix.mjs, then packs the starter
// as public/download/tuberemix-starter.zip and public/download/starter-files.json (used by the
// in-browser "Starter project" export, which swaps in the user's own config).
import { build } from "esbuild";
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { writeZip } from "../src/core/zip";

const root = resolve(import.meta.dirname, "..");
const starter = join(root, "starter");

await build({
  entryPoints: [join(root, "src/starter-entry.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: join(starter, "lib/tuberemix.mjs"),
  banner: { js: "// Generated by TubeRemix (scripts/build-starter.ts) from its src/core and src/pipeline. MIT licensed. Do not edit." },
  legalComments: "inline",
  logLevel: "warning",
});

const SKIP = new Set([".cache", "dist", "node_modules"]);
function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    if (SKIP.has(n)) return [];
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}
const files = walk(starter).map((p) => relative(starter, p).split(String.fromCharCode(92)).join("/")).sort();
const map: Record<string, string> = {};
for (const f of files) map[f] = readFileSync(join(starter, f), "utf8").split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));

const out = join(root, "public/download");
mkdirSync(out, { recursive: true });
writeFileSync(join(out, "starter-files.json"), JSON.stringify(map));
writeFileSync(join(out, "tuberemix-starter.zip"), writeZip(files.map((f) => ({ name: `my-tube/${f}`, data: map[f]! }))));
console.log(`starter: ${files.length} files -> public/download/tuberemix-starter.zip`);
